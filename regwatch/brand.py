"""Фирменный стиль: единственный источник цветов и шрифтов.

Отсюда берут оформление и отчёт, и веб-приложение, и PDF. Держать палитру
в одном месте важнее, чем кажется: раньше цвета были вписаны прямо в разметку
отчёта, и любая правка требовала пройти по всему файлу, ничего не забыв.

Откуда цвета
------------
Сняты с сайта fgiis.ru — не подобраны на глаз и не пересчитаны из Pantone.
Два ключевых совпали с брендбуком буквально: фон #F6F7F8 и бирюза #06b6cb
стоят на сайте именно такими.

Характер темы ФГИИС: светлая и просторная. Текст графитовый, а не цветной;
фон почти белый; бирюза работает тонкими линиями и мелкими деталями, а не
заливками во всю ширину. Второй акцент — коралловый — на сайте появляется
точечно, поэтому здесь он достался только пометке «требует решения».

Доступность
-----------
Все сочетания проверены по WCAG AA (4.5:1) на белом И на сером фоне страницы:
серый темнее, и мерить надо по худшему случаю. Два следствия приняты
как данность:

* **на бирюзе белый текст нечитаем** (2.29:1) — она годится под тёмный текст,
  линиями и рамками, но никогда не становится фоном под белый;
* **фирменные бирюза и коралл сами по себе слишком светлые для текста** —
  для надписей служат затемнённые accent_ink и coral_ink.
"""
from __future__ import annotations

# --------------------------------------------------------------- цвета

INK = "#313132"        # графит — заголовки (fgiis.ru)
ACCENT = "#06b6cb"     # бирюза — акцент (fgiis.ru)
CORAL = "#FF8562"      # второй акцент (fgiis.ru)
PAPER = "#F6F7F8"      # фон страницы (fgiis.ru)

COLORS = {
    "ink": INK,                 # заголовки                 12.12:1
    "ink_80": "#4a4a4c",        # подзаголовки
    "ink_65": "#717172",        # основной текст             4.55:1
    "ink_45": "#6f7074",        # подписи                    4.61:1
    "accent": ACCENT,
    "accent_ink": "#197b88",    # бирюза для текста и ссылок 4.63:1
    "accent_soft": "#e7f8fa",   # подложка под тёмный текст
    "accent_edge": "#a9e4ec",   # тонкая рамка
    "accent_line": "#5ccedb",   # заметная линия
    "coral": CORAL,
    "coral_ink": "#ab5942",     # коралл для текста          4.62:1
    "coral_soft": "#fff1ec",
    "surface": "#eef1f4",       # светлая подложка (fgiis.ru)
    "paper": PAPER,
    "white": "#ffffff",
    "line": "#dcdfe3",          # границы
    "line_soft": "#e8ebee",     # разделители внутри блоков
}

# Семантика срочности. Приглушена намеренно: у ФГИИС спокойная светлая тема,
# и яркий «светофор» в ней выглядит чужеродно. Вес несут порядок разделов
# и подписи, цвет — только подсказка.
URGENCY = {
    "critical": {"label": "Требует решения", "color": "#a65640", "soft": "#fff1ec"},
    "high":     {"label": "Важное",          "color": "#8a6a2f", "soft": "#f7f3ea"},
    "normal":   {"label": "К сведению",      "color": "#197b88", "soft": "#e7f8fa"},
    "low":      {"label": "Прочее",          "color": "#696a6e", "soft": "#eef1f4"},
}

# Органы различаются не заливкой, а оттенком подписи: несколько разноцветных
# плашек на странице спорят друг с другом и с акцентом. Оттенки сдержанные,
# в одном тоне с графитом.
AUTHORITY = {
    "ЦБ": "#313132", "ГД": "#6d3a4e", "Минфин": "#2d5266",
    "СФ": "#3c4665", "Правительство": "#2f5d55", "Президент": "#6b5427",
    "СМИ": "#717172",
}

# --------------------------------------------------------------- шрифт

FONT_NAME = "Inter"
FONT_URL = ("https://fonts.googleapis.com/css2?"
            "family=Inter:wght@400;500;600;700&display=swap")

# Запасные шрифты подобраны так, чтобы при недоступности Inter метрики
# не поехали: San Francisco на Mac и Segoe UI на Windows близки по ширине.
FONT_STACK = ("'Inter','Inter var',-apple-system,BlinkMacSystemFont,"
              "'SF Pro Text','Segoe UI',Roboto,Helvetica,Arial,sans-serif")

# Цифры в таблицах и сводках должны стоять столбиком — иначе взгляд
# спотыкается при сравнении чисел разной ширины.
FONT_NUMERIC = "font-variant-numeric:tabular-nums;font-feature-settings:'tnum' 1;"


def css_variables() -> str:
    """Палитра как CSS-переменные — для веб-приложения."""
    lines = [f"  --{k.replace('_', '-')}: {v};" for k, v in COLORS.items()]
    for level, meta in URGENCY.items():
        lines.append(f"  --u-{level}: {meta['color']};")
        lines.append(f"  --u-{level}-soft: {meta['soft']};")
    return ":root{\n" + "\n".join(lines) + "\n}"


def c(name: str) -> str:
    """Короткий доступ к цвету: c('ink_65')."""
    return COLORS[name]
